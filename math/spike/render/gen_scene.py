"""Build the spike's scene through the real engine and write ``scene.js``.

Run from the engine project so its environment is used::

    cd math/python/engine && uv run python ../../spike/render/gen_scene.py

Every curve is plotted with ``plot.explicit`` and translated with ``code.glsl``; nothing in
``scene.js`` is written by hand. Each curve has its own two or three parameters (``p3a`` is
parameter a of curve 3) with a slider range, which the page sweeps to simulate a drag.
"""

from __future__ import annotations

import json
from pathlib import Path

from fibration_math_engine.engine import Engine
from fibration_math_engine.glsl import PRELUDE, glsl

# (expression in a, b, c; {param: (value, min, max)})
CURVES = [
    ("a*sin(b*x) + c*x", {"a": (2, 0.5, 4), "b": (1, 0.3, 3), "c": (0.2, -0.5, 0.5)}),
    ("a*sin(b*x) + c*x", {"a": (1, 0.5, 3), "b": (2.5, 1, 5), "c": (-0.3, -0.6, 0.2)}),
    ("a*cos(b*x)*exp(-c*abs(x))", {"a": (4, 1, 5), "b": (3, 1, 6), "c": (0.3, 0.05, 0.8)}),
    ("a*sin(b*x)/x", {"a": (5, 1, 6), "b": (2, 0.5, 5)}),
    ("a/(x**2 + b)", {"a": (6, 1, 12), "b": (1.5, 0.3, 4)}),
    ("a*x/(x**2 + b**2)", {"a": (6, 1, 10), "b": (1, 0.3, 3)}),
    ("(x**2 - a)/(x**2 + b)*c", {"a": (4, 0, 9), "b": (2, 0.5, 6), "c": (3, 1, 5)}),
    ("a/x + b", {"a": (2, 0.5, 5), "b": (0, -2, 2)}),
    ("a*exp(-b*x**2) + c", {"a": (4, 1, 5), "b": (0.2, 0.02, 1), "c": (-1, -3, 1)}),
    ("a*log(x**2 + b) - c", {"a": (1, 0.3, 2), "b": (1, 0.1, 5), "c": (2, 0, 4)}),
    ("b*exp(a*x)/(1 + exp(a*x)) - c", {"a": (1, 0.2, 4), "b": (5, 1, 6), "c": (2, 0, 4)}),
    ("a*x*exp(-b*abs(x))", {"a": (5, 1, 9), "b": (0.5, 0.1, 1.5)}),
    ("a*x**3/50 + b*x", {"a": (1, -2, 2), "b": (-0.5, -2, 2)}),
    ("a*x**2/10 - b", {"a": (1, -2, 2), "b": (3, 0, 5)}),
    ("a*sqrt(abs(x)) + b*sin(x)", {"a": (1, -2, 2), "b": (1, 0, 2)}),
    ("a*tanh(b*x) + c", {"a": (3, 1, 5), "b": (1, 0.2, 5), "c": (0, -2, 2)}),
    ("a*atan(b*x)", {"a": (2, 0.5, 3.5), "b": (1, 0.2, 8)}),
    ("a*abs(sin(b*x)) - c", {"a": (2, 0.5, 4), "b": (1, 0.3, 3), "c": (4, 2, 5)}),
    ("floor(a*x)/b", {"a": (1, 0.3, 2), "b": (2, 1, 4)}),
    ("b*tan(a*x)", {"a": (0.4, 0.2, 0.9), "b": (1, 0.3, 2)}),
]
IMPLICIT = ("y**2 = x**3 - a*x + b", {"a": (3, 1, 6), "b": (1, -2, 4)})  # an elliptic curve
REGION = ("(x - 5)**2 + (y - b)**2 < a", {"a": (3, 1, 6), "b": (2, -2, 3)})


def call(engine: Engine, fn: str, **args):
    out = engine.call(fn, args)
    if out["status"] != "ok":
        raise SystemExit(f"{fn} {args}: {out['error']}")
    return out["value"]


def add(engine: Engine, fn: str, key: str, prefix: str, text: str, params: dict, **extra) -> dict:
    ranges = {}
    for name, (value, lo, hi) in params.items():
        full = f"{prefix}{name}"
        call(engine, "param.declare", name=full, value=value, min=lo, max=hi)
        ranges[f"u_{full}"] = (lo, hi)
        text = _rename(text, name, full)
    oid = call(engine, fn, **{key: text}, id=prefix, **extra)["id"]
    out = glsl(engine, oid)
    if not out["supported"]:
        raise SystemExit(f"{text}: {out['reason']}")
    return {
        "id": oid,
        "text": text,
        "glsl": out["glsl"],
        "uniforms": [{**u, "min": ranges[u["name"]][0], "max": ranges[u["name"]][1]} for u in out["uniforms"]],
    }


def _rename(text: str, name: str, full: str) -> str:
    """Replace the whole-word parameter name (a, b, c) in math text."""
    import re

    return re.sub(rf"(?<![A-Za-z0-9_]){name}(?![A-Za-z0-9_(])", full, text)


def main() -> None:
    engine = Engine()
    curves = [
        add(engine, "plot.explicit", "expr", f"p{i}", text, params, var="x")
        for i, (text, params) in enumerate(CURVES)
    ]
    implicit = add(engine, "plot.implicit", "equation", "imp", *IMPLICIT, x="x", y="y")
    region = add(engine, "plot.region", "condition", "reg", *REGION, x="x", y="y")
    scene = {"prelude": PRELUDE, "curves": curves, "implicit": implicit, "region": region}
    target = Path(__file__).with_name("scene.js")
    target.write_text(
        "// Generated by gen_scene.py from the Fibration Math engine (code.glsl). Do not edit.\n"
        f"window.SPIKE_SCENE = {json.dumps(scene, indent=1)};\n",
        "utf-8",
    )
    print(f"wrote {target} ({len(curves)} curves)")


if __name__ == "__main__":
    main()
