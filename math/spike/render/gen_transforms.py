"""Build the nonlinear maps of the transforms spike through the real engine.

Run from the engine project so its environment is used::

    cd math/python/engine && uv run python ../../spike/render/gen_transforms.py

A map (x, y) -> (u, v) has no scene object of its own yet, so each component is plotted as the
implicit relation ``u(x, y) = 0`` and ``code.glsl`` gives ``float F(vec2 xy)`` for it, which is
exactly the component as a function of the point. The functions are renamed (``Fu_<map>``,
``Fv_<map>``) and written to ``transforms_scene.js``. Nothing in that file is written by hand.
The surface of the 3D scene is produced the same way from ``z - f(x, y) = 0``.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from fibration_math_engine.engine import Engine
from fibration_math_engine.glsl import PRELUDE, glsl

# name -> (u, v, {param: (value, min, max)})
MAPS = {
    "square": ("(x**2 - y**2)/c", "2*x*y/c", {"c": (6, 4, 10)}),
    "swirl": (
        "x*cos(k*exp(-(x**2 + y**2)/w)) - y*sin(k*exp(-(x**2 + y**2)/w))",
        "x*sin(k*exp(-(x**2 + y**2)/w)) + y*cos(k*exp(-(x**2 + y**2)/w))",
        {"k": (2, -3, 3), "w": (30, 10, 60)},
    ),
}
SURFACE = ("a*sin(x)*cos(b*y)", {"a": (1.5, 0.5, 2.5), "b": (1, 0.5, 2)})


def call(engine: Engine, fn: str, **args):
    out = engine.call(fn, args)
    if out["status"] != "ok":
        raise SystemExit(f"{fn} {args}: {out['error']}")
    return out["value"]


def component(engine: Engine, text: str, oid: str, fname: str) -> tuple[str, list]:
    call(engine, "plot.implicit", equation=text, x="x", y="y", id=oid)
    out = glsl(engine, oid)
    if not out["supported"]:
        raise SystemExit(f"{text}: {out['reason']}")
    code, n = re.subn(r"\bfloat F\(", f"float {fname}(", out["glsl"])
    assert n == 1, out["glsl"]
    return code, out["uniforms"]


def main() -> None:
    engine = Engine()
    scene: dict = {"prelude": PRELUDE, "maps": {}}
    for name, (u, v, params) in MAPS.items():
        ranges = {}
        for p, (value, lo, hi) in params.items():
            full = f"{name}_{p}"
            call(engine, "param.declare", name=full, value=value, min=lo, max=hi)
            ranges[f"u_{full}"] = (lo, hi)
            u = re.sub(rf"(?<![A-Za-z0-9_]){p}(?![A-Za-z0-9_(])", full, u)
            v = re.sub(rf"(?<![A-Za-z0-9_]){p}(?![A-Za-z0-9_(])", full, v)
        cu, uu = component(engine, u, f"{name}-u", f"Fu_{name}")
        cv, uv = component(engine, v, f"{name}-v", f"Fv_{name}")
        uniforms = {x["name"]: x for x in [*uu, *uv]}
        scene["maps"][name] = {
            "u": u, "v": v, "glsl": cu + "\n" + cv,
            "uniforms": [{**x, "min": ranges[x["name"]][0], "max": ranges[x["name"]][1]} for x in uniforms.values()],
        }
    text, params = SURFACE
    ranges = {}
    for p, (value, lo, hi) in params.items():
        full = f"surf_{p}"
        call(engine, "param.declare", name=full, value=value, min=lo, max=hi)
        ranges[f"u_{full}"] = (lo, hi)
        text = re.sub(rf"(?<![A-Za-z0-9_]){p}(?![A-Za-z0-9_(])", full, text)
    code, uniforms = component(engine, text, "surface", "Fsurf")
    scene["surface"] = {
        "text": text, "glsl": code,
        "uniforms": [{**x, "min": ranges[x["name"]][0], "max": ranges[x["name"]][1]} for x in uniforms],
    }
    target = Path(__file__).with_name("transforms_scene.js")
    target.write_text(
        "// Generated by gen_transforms.py from the Fibration Math engine (code.glsl). Do not edit.\n"
        f"window.TRANSFORMS_SCENE = {json.dumps(scene, indent=1)};\n",
        "utf-8",
    )
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
