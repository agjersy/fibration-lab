//! Writes the TypeScript bindings of every UI-facing deck type to the one renderer's
//! `apps/desktop/src/ipc/generated/deck/`, plus an `index.ts` that re-exports them. The
//! analysis types next to them come from `analyst-protocol`.

use analyst_deck_protocol::cite::{Cite, RefKind};
use analyst_deck_protocol::config::{ContractConfig, ExportPreset};
use analyst_deck_protocol::deck::{Deck, Slide, Table};
use analyst_deck_protocol::ids::{ElementId, RefId, SlideId};
use analyst_deck_protocol::kernel::{
    AnalystScanResult, ChartComputeResult, Chunk, Diagnostic, ElementMapEntry, HelloResult,
    ImageRef, LayoutThumbnail, Notification, OutlineNode, TableRef,
};
use analyst_deck_protocol::template::{TemplateDescription, TemplateSidecar};
use analyst_deck_protocol::ui;
use std::path::Path;
use ts_rs::TS;

#[test]
fn export_typescript_bindings() {
    let dir =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../apps/desktop/src/ipc/generated/deck");
    std::fs::create_dir_all(&dir).unwrap();
    let dir = dir.canonicalize().unwrap();
    // The directory holds ts-rs output only: start clean so stale files never linger.
    for entry in std::fs::read_dir(&dir).unwrap().flatten() {
        let p = entry.path();
        if p.extension().map(|e| e == "ts").unwrap_or(false) {
            std::fs::remove_file(&p).unwrap();
        }
    }
    let cfg = ts_rs::Config::new()
        .with_out_dir(&dir)
        .with_large_int("number");
    // Root types; dependencies are exported alongside.
    Deck::export_all(&cfg).unwrap();
    Slide::export_all(&cfg).unwrap();
    Table::export_all(&cfg).unwrap();
    Cite::export_all(&cfg).unwrap();
    RefKind::export_all(&cfg).unwrap();
    SlideId::export_all(&cfg).unwrap();
    ElementId::export_all(&cfg).unwrap();
    RefId::export_all(&cfg).unwrap();
    TemplateDescription::export_all(&cfg).unwrap();
    TemplateSidecar::export_all(&cfg).unwrap();
    Diagnostic::export_all(&cfg).unwrap();
    HelloResult::export_all(&cfg).unwrap();
    ElementMapEntry::export_all(&cfg).unwrap();
    LayoutThumbnail::export_all(&cfg).unwrap();
    OutlineNode::export_all(&cfg).unwrap();
    Chunk::export_all(&cfg).unwrap();
    TableRef::export_all(&cfg).unwrap();
    ImageRef::export_all(&cfg).unwrap();
    ChartComputeResult::export_all(&cfg).unwrap();
    AnalystScanResult::export_all(&cfg).unwrap();
    Notification::export_all(&cfg).unwrap();
    ContractConfig::export_all(&cfg).unwrap();
    ExportPreset::export_all(&cfg).unwrap();
    // Desktop IPC (IPC.md).
    ui::IpcError::export_all(&cfg).unwrap();
    ui::DeckInfo::export_all(&cfg).unwrap();
    ui::SlideView::export_all(&cfg).unwrap();
    ui::DeckView::export_all(&cfg).unwrap();
    ui::RefView::export_all(&cfg).unwrap();
    ui::SourcePassage::export_all(&cfg).unwrap();
    ui::SearchHit::export_all(&cfg).unwrap();
    ui::ExportView::export_all(&cfg).unwrap();
    ui::AssetView::export_all(&cfg).unwrap();
    ui::FileContent::export_all(&cfg).unwrap();
    ui::WriteResult::export_all(&cfg).unwrap();
    ui::DeckEvent::export_all(&cfg).unwrap();

    let mut names: Vec<String> = std::fs::read_dir(&dir)
        .unwrap()
        .flatten()
        .filter_map(|e| {
            let p = e.path();
            let stem = p.file_stem()?.to_string_lossy().to_string();
            (p.extension()? == "ts" && stem != "index").then_some(stem)
        })
        .collect();
    names.sort();
    let mut index = String::from(
        "// This file was generated by analyst-deck-protocol (`cargo test -p analyst-deck-protocol`). Do not edit it manually.\n\n",
    );
    for n in &names {
        index.push_str(&format!("export type {{ {n} }} from \"./{n}\";\n"));
    }
    std::fs::write(dir.join("index.ts"), index).unwrap();

    for expected in [
        "Deck",
        "Slide",
        "PlaceholderContent",
        "ElementContent",
        "Diagram",
        "TransformStep",
        "Cite",
        "Table",
        "TemplateDescription",
        "LayoutInfo",
        "Diagnostic",
        "SandboxInfo",
        "EngineInfo",
        "EmbeddingInfo",
        "DeckEvent",
        "DeckInfo",
    ] {
        assert!(
            names.iter().any(|n| n == expected),
            "{expected}.ts was not written"
        );
    }
    let read = |name: &str| std::fs::read_to_string(dir.join(format!("{name}.ts"))).unwrap();
    assert!(read("SlideId").contains("export type SlideId = string;"));
    assert!(read("Cite").contains("export type Cite = string;"));
    // Tags and optional fields as written in PROTOCOL 2.
    let content = read("PlaceholderContent");
    assert!(content.contains("\"type\": \"empty\""), "{content}");
    let run = read("Run");
    assert!(run.contains("cite?: Array<Cite>"), "{run}");
    let step = read("TransformStep");
    assert!(step.contains("\"op\": \"pct_change\""), "{step}");
    assert!(step.contains("as?: string"), "{step}");
    let diagram = read("Diagram");
    assert!(diagram.contains("\"family\": \"hierarchy\""), "{diagram}");
    let chart = read("Chart");
    assert!(chart.contains("type: ChartType"), "{chart}");
    assert!(!chart.contains("bigint"), "{chart}");
}
