//! Template description (PROTOCOL 3) and the template sidecar `template/template.toml`
//! (PROTOCOL 6.4).

use crate::deck::{PlaceholderKey, Size, ThemeColor};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use ts_rs::TS;

/// Result of `template.inspect`, cached at `.present/cache/template-<sha256>.json`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, TS)]
pub struct TemplateDescription {
    pub path: String,
    pub sha256: String,
    pub slide_size: Size,
    pub theme: Theme,
    pub masters: Vec<MasterInfo>,
    pub table_styles: Vec<TableStyle>,
    /// Id of the table style new tables use, when the template names one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub default_table_style: Option<String>,
    /// Theme or placeholder fonts not installed on this machine.
    pub fonts_missing: Vec<String>,
}

impl TemplateDescription {
    /// Every layout of every master, in template order.
    pub fn layouts(&self) -> impl Iterator<Item = &LayoutInfo> {
        self.masters.iter().flat_map(|m| m.layouts.iter())
    }

    pub fn layout(&self, name: &str) -> Option<&LayoutInfo> {
        self.layouts().find(|l| l.name == name)
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema, TS)]
pub struct Theme {
    pub name: String,
    /// Hex color (`"1F3864"`-style, as the kernel reports it) per theme slot.
    pub colors: BTreeMap<ThemeColor, String>,
    pub fonts: ThemeFonts,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema, TS)]
pub struct ThemeFonts {
    pub major: String,
    pub minor: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub ea: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub cs: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, TS)]
pub struct MasterInfo {
    pub name: String,
    pub layouts: Vec<LayoutInfo>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema, TS)]
pub struct TableStyle {
    pub id: String,
    pub name: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, TS)]
pub struct LayoutInfo {
    pub name: String,
    pub master: String,
    pub index: u32,
    /// From the sidecar, or generated by the agent and cached.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub description: Option<String>,
    pub placeholders: Vec<PlaceholderInfo>,
    /// False if the sidecar marks it avoid, or it has no fillable placeholders.
    pub usable: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, TS)]
pub struct PlaceholderInfo {
    /// Role name, made unique with a suffix (`"body"`, `"body-2"`), or `"idx:<n>"`.
    pub key: PlaceholderKey,
    pub r#type: PlaceholderType,
    pub idx: u32,
    pub x: i64,
    pub y: i64,
    pub cx: i64,
    pub cy: i64,
    pub autofit: Autofit,
    /// Vertical anchor of the text body as OOXML writes it (`"t"`, `"ctr"`, `"b"`, ...).
    pub anchor: String,
    pub levels: Vec<LevelStyle>,
    pub insets: Insets,
    pub accepts: Vec<ContentKind>,
}

/// OOXML placeholder type (`p:ph/@type`).
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, schemars::JsonSchema, TS,
)]
#[serde(rename_all = "camelCase")]
pub enum PlaceholderType {
    Title,
    CtrTitle,
    SubTitle,
    Body,
    Obj,
    Pic,
    Chart,
    Tbl,
    Dgm,
    Media,
    ClipArt,
    Dt,
    Ftr,
    SldNum,
}

#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Eq,
    Hash,
    Default,
    Serialize,
    Deserialize,
    schemars::JsonSchema,
    TS,
)]
#[serde(rename_all = "lowercase")]
pub enum Autofit {
    #[default]
    None,
    Shrink,
    Resize,
}

/// Text style of one indent level of a placeholder.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, schemars::JsonSchema, TS)]
pub struct LevelStyle {
    pub level: u32,
    pub font: String,
    pub size_pt: f64,
    pub bold: bool,
    pub color: LevelColor,
    pub bullet: bool,
    pub space_before_pt: f64,
    pub line_spacing: f64,
    /// Left margin of the level, EMU.
    pub mar_l: i64,
}

/// `ThemeColor | string`: a theme slot, or a hex color the template hard-codes.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema, TS)]
#[serde(untagged)]
pub enum LevelColor {
    Theme(ThemeColor),
    Hex(String),
}

/// Text box insets in EMU.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize, schemars::JsonSchema, TS,
)]
pub struct Insets {
    pub l: i64,
    pub t: i64,
    pub r: i64,
    pub b: i64,
}

/// A content type a placeholder accepts; the `type` tags of
/// [`crate::deck::PlaceholderContent`] other than `empty`.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, schemars::JsonSchema, TS,
)]
#[serde(rename_all = "lowercase")]
pub enum ContentKind {
    Text,
    Image,
    Chart,
    Table,
    Diagram,
}

// ---- sidecar (6.4) ----

/// `template/template.toml`; result of `template.sidecar`.
#[derive(
    Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize, schemars::JsonSchema, TS,
)]
#[serde(default)]
pub struct TemplateSidecar {
    pub template: SidecarTemplate,
    /// Keyed by layout name.
    #[serde(skip_serializing_if = "BTreeMap::is_empty")]
    pub layouts: BTreeMap<String, SidecarLayout>,
    pub rules: SidecarRules,
}

#[derive(
    Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize, schemars::JsonSchema, TS,
)]
pub struct SidecarTemplate {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub name: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub owner: Option<String>,
}

#[derive(
    Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize, schemars::JsonSchema, TS,
)]
pub struct SidecarLayout {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub description: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub use_for: Option<String>,
    /// Overrides the contract's `max_bullets` for this layout (rule `density.bullets`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub max_bullets: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub avoid: Option<bool>,
}

#[derive(
    Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize, schemars::JsonSchema, TS,
)]
pub struct SidecarRules {
    /// Layouts that must appear at least once.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub mandatory: Vec<String>,
    /// Layout of the last slide.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub closing: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub allow_free_elements: Option<bool>,
    /// Relative to `template/`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub icons_dir: Option<String>,
}
